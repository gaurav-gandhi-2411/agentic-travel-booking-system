"""Wave 2 Tier-2 eval judge — scores optimizer explanation quality via local Ollama.

Reads a run JSONL (generated by runner.py), calls an Ollama judge model for
each record that has optimizer_archetypes, and produces per-criterion quality
scores + a markdown report.

Graceful skips:
- Ollama not running: prints "judge skipped — Ollama unavailable" and exits 0
- Record has no optimizer_archetypes: skipped (Tier-1-only run or planner failed)

Judge model: qwen3:8b (different family from Groq Llama generator; no self-grading
bias). qwen3 separates chain-of-thought into message.thinking; message.content is
clean JSON.

Usage:
    # Judge latest run file with default model
    python -m evals.wave2.judge

    # Judge a specific run file
    python -m evals.wave2.judge --run runs/20260621T120000_demo-llama.jsonl

    # Use a different local judge model
    python -m evals.wave2.judge --judge-model gemma2:9b
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path
from typing import Any

import httpx

_RUNS_DIR = Path(__file__).parent / "runs"
_REPORTS_DIR = Path(__file__).parent / "reports"
_OLLAMA_BASE = "http://localhost:11434"
_DEFAULT_JUDGE_MODEL = "qwen3:8b"
_QUALITY_WARN = 3.0

# Criteria scored 1-5 per archetype.
# Each key maps to the JSON field name returned by the judge.
_CRITERIA = {
    "explanation_accuracy": (
        "Does the explanation accurately describe the actual flight? "
        "(5=all facts correct: airline, stops, price tier, time period; 1=contains errors)"
    ),
    "explanation_relevance": (
        "Is the explanation specific to this user's query? "
        "(5=directly addresses query intent; 1=generic filler with no query-specific detail)"
    ),
    "comparison_coherence": (
        "Does 'why this over the other?' make a logical case given the two actual archetypes? "
        "(5=coherent trade-off, grounded in real differences; 1=incoherent or contradicts data)"
    ),
}


def _build_judge_prompt(query: str, archetypes: list[dict[str, Any]]) -> str:
    sections: list[str] = [
        f"QUERY: {query!r}",
        "",
        "Evaluate the travel agent's archetype recommendations below.",
        "",
    ]

    for i, arch in enumerate(archetypes):
        label = arch.get("label", f"archetype_{i}")
        flight = arch.get("flight", {})
        airline = flight.get("airline_code", "?")
        fn = flight.get("flight_number", "?")
        origin = flight.get("origin_iata", "?")
        dest = flight.get("destination_iata", "?")
        depart = (flight.get("outbound_departure_at", "?") or "?")[:16]
        stops = flight.get("layover_count", "?")
        price = flight.get("price_inr", "?")
        explanation = arch.get("explanation", "")
        comparison = arch.get("comparison_to_alternative", "")

        stop_str = "non-stop" if stops == 0 else f"{stops} stop(s)"
        sections += [
            f"ARCHETYPE {i + 1} ({label}):",
            f"  Flight: {airline} {fn}  {origin}→{dest}  {depart}  {stop_str}  ₹{price:,}",
            f"  Explanation: {explanation!r}",
            f"  Why vs alternative: {comparison!r}",
            "",
        ]

    criteria_lines = "\n".join(
        f"- {key}: {desc}" for key, desc in _CRITERIA.items()
    )
    schema_fields = ",\n  ".join(
        f'"arch_{i + 1}_{key}": 1_to_5'
        for i in range(len(archetypes))
        for key in _CRITERIA
    )
    sections += [
        "Score each criterion 1-5 using these definitions:",
        criteria_lines,
        "",
        "Return ONLY valid JSON, nothing else:",
        "{",
        f"  {schema_fields},",
        '  "rationale": "one sentence summary of overall quality"',
        "}",
    ]
    return "\n".join(sections)


async def _call_judge(
    prompt: str,
    model: str,
    client: httpx.AsyncClient,
) -> dict[str, Any] | None:
    """Call Ollama and parse JSON from message.content. Returns None on failure."""
    payload = {
        "model": model,
        "messages": [
            {"role": "system", "content": "You are a quality evaluator. Return only valid JSON."},
            {"role": "user", "content": prompt},
        ],
        "stream": False,
        "options": {"temperature": 0, "num_predict": 600},
    }
    try:
        resp = await client.post(f"{_OLLAMA_BASE}/api/chat", json=payload, timeout=120.0)
        resp.raise_for_status()
        content: str = resp.json()["message"]["content"]
        s = content.find("{")
        e = content.rfind("}")
        if s < 0 or e <= s:
            _logger_print(f"  [judge] no JSON braces in response: {content[:80]!r}")
            return None
        return json.loads(content[s : e + 1])
    except Exception as exc:
        _logger_print(f"  [judge] call failed: {exc}")
        return None


def _logger_print(msg: str) -> None:
    print(msg)


async def _check_ollama(model: str, client: httpx.AsyncClient) -> bool:
    """Return True if Ollama is reachable and the model is available."""
    try:
        r = await client.get(f"{_OLLAMA_BASE}/api/tags", timeout=5.0)
        r.raise_for_status()
        models = [m["name"] for m in r.json().get("models", [])]
        base = model.split(":", maxsplit=1)[0]
        return any(m.startswith(base) for m in models)
    except Exception:
        return False


def _load_run(run_path: Path | None) -> tuple[Path, list[dict[str, Any]]]:
    if run_path is None:
        files = sorted(_RUNS_DIR.glob("*.jsonl"))
        if not files:
            return Path("(none)"), []
        run_path = files[-1]
    lines = run_path.read_text(encoding="utf-8").splitlines()
    records = [json.loads(ln) for ln in lines if ln.strip()]
    return run_path, records


def _avg(values: list[float]) -> float:
    return sum(values) / len(values) if values else 0.0


async def judge_run(
    records: list[dict[str, Any]],
    judge_model: str,
    client: httpx.AsyncClient,
) -> list[dict[str, Any]]:
    results: list[dict[str, Any]] = []
    for rec in records:
        cid = rec["id"]
        archetypes = rec.get("optimizer_archetypes")
        if not archetypes:
            results.append({"id": cid, "skipped": True, "reason": "no optimizer_archetypes"})
            continue

        query = rec.get("query", "")
        prompt = _build_judge_prompt(query, archetypes)
        t0 = time.monotonic()
        scores = await _call_judge(prompt, judge_model, client)
        latency = round((time.monotonic() - t0) * 1000, 1)

        if scores is None:
            results.append({"id": cid, "skipped": True, "reason": "judge call failed"})
            continue

        # Collect numeric scores across all arch_N_criterion keys
        numeric: list[float] = []
        per_arch: list[dict[str, Any]] = []
        for i, arch in enumerate(archetypes):
            arch_scores: dict[str, Any] = {"label": arch.get("label", f"arch_{i + 1}")}
            for key in _CRITERIA:
                field = f"arch_{i + 1}_{key}"
                val = scores.get(field)
                try:
                    fval = float(val)  # type: ignore[arg-type]
                    arch_scores[key] = fval
                    numeric.append(fval)
                except (TypeError, ValueError):
                    arch_scores[key] = None
            per_arch.append(arch_scores)

        results.append({
            "id": cid,
            "skipped": False,
            "query": query,
            "per_arch": per_arch,
            "overall_quality": round(_avg(numeric), 2),
            "rationale": scores.get("rationale", ""),
            "latency_ms_judge": latency,
            "judge_model": judge_model,
            "raw_scores": scores,
        })
        print(
            f"  [{cid}] quality={_avg(numeric):.2f}  {scores.get('rationale', '')[:60]}"
        )

    return results


def _print_report(results: list[dict[str, Any]], run_path: Path, judge_model: str) -> None:
    judged = [r for r in results if not r.get("skipped")]
    skipped = [r for r in results if r.get("skipped")]

    print("\n" + "=" * 62)
    print(f"Wave 2 Tier-2 Judge Report  —  {judge_model}")
    print(f"Run: {run_path.name}")
    print(f"Judged: {len(judged)}  Skipped: {len(skipped)}")
    print("=" * 62)

    if not judged:
        print("No cases judged — no optimizer_archetypes in run file.")
        print("Re-run the runner without --no-optimizer to generate them.")
        return

    # Per-criterion aggregate
    crit_scores: dict[str, list[float]] = {k: [] for k in _CRITERIA}
    for r in judged:
        for arch in r.get("per_arch", []):
            for key in _CRITERIA:
                val = arch.get(key)
                if val is not None:
                    crit_scores[key].append(float(val))

    print("\nAGGREGATE QUALITY SCORES  (1-5 scale)")
    for key, vals in crit_scores.items():
        print(f"  {key:<32}  {_avg(vals):.2f}  (n={len(vals)})")

    overall_vals = [r["overall_quality"] for r in judged]
    print(f"\n  {'OVERALL':<32}  {_avg(overall_vals):.2f}")

    print("\nPER-CASE DETAIL")
    for r in sorted(judged, key=lambda x: x["overall_quality"]):
        q = r["overall_quality"]
        flag = " !" if q < _QUALITY_WARN else ""
        print(f"  {r['id']}  {q:.2f}{flag}  {r.get('rationale', '')[:55]}")

    if skipped:
        print(f"\nSKIPPED ({len(skipped)} cases):")
        for r in skipped:
            print(f"  {r['id']}: {r.get('reason', '?')}")


def _write_md_report(
    results: list[dict[str, Any]],
    run_path: Path,
    judge_model: str,
) -> Path:
    from datetime import UTC, datetime  # noqa: PLC0415
    ts = datetime.now(tz=UTC).strftime("%Y%m%dT%H%M%S")
    judged = [r for r in results if not r.get("skipped")]

    lines: list[str] = [
        "# Wave 2 Tier-2 Quality Report",
        "",
        f"**Judge model:** `{judge_model}`  ",
        f"**Run file:** `{run_path.name}`  ",
        f"**Judged:** {len(judged)} / {len(results)} cases  ",
        "",
        "## Aggregate Scores (1-5)",
        "",
        "| Criterion | Score |",
        "|-----------|-------|",
    ]

    if judged:
        crit_scores: dict[str, list[float]] = {k: [] for k in _CRITERIA}
        for r in judged:
            for arch in r.get("per_arch", []):
                for key in _CRITERIA:
                    val = arch.get(key)
                    if val is not None:
                        crit_scores[key].append(float(val))
        for key, vals in crit_scores.items():
            lines.append(f"| {key} | {_avg(vals):.2f} |")
        overall_vals = [r["overall_quality"] for r in judged]
        lines += [f"| **OVERALL** | **{_avg(overall_vals):.2f}** |", ""]

    lines += ["## Per-Case Results", "", "| ID | Quality | Rationale |", "|---|---|---|"]
    for r in sorted(results, key=lambda x: (x.get("skipped", False), -x.get("overall_quality", 0))):
        if r.get("skipped"):
            lines.append(f"| `{r['id']}` | skipped | {r.get('reason', '')} |")
        else:
            rat = r.get("rationale", "").replace("|", "\\|")
            lines.append(f"| `{r['id']}` | {r['overall_quality']:.2f} | {rat} |")

    out = _REPORTS_DIR / f"{ts}_{run_path.stem}_tier2.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out


async def main() -> int:
    parser = argparse.ArgumentParser(description="Wave 2 Tier-2 quality judge (local Ollama)")
    parser.add_argument("--run", help="Run JSONL file (default: latest in runs/)")
    parser.add_argument(
        "--judge-model", default=_DEFAULT_JUDGE_MODEL,
        help=f"Ollama model for judging (default: {_DEFAULT_JUDGE_MODEL})",
    )
    args = parser.parse_args()

    run_path_arg = Path(args.run) if args.run else None
    run_path, records = _load_run(run_path_arg)

    if not records:
        print("No baseline run found. Run: python -m evals.wave2.runner")
        return 0

    print(f"Run: {run_path.name}  ({len(records)} records)")

    async with httpx.AsyncClient() as client:
        available = await _check_ollama(args.judge_model, client)
        if not available:
            print(
                f"judge skipped — Ollama unavailable or model {args.judge_model!r} not found\n"
                f"  Start Ollama and run: ollama pull {args.judge_model}"
            )
            return 0

        print(f"Judge model: {args.judge_model}  (Ollama OK)")
        results = await judge_run(records, args.judge_model, client)

    _print_report(results, run_path, args.judge_model)
    out = _write_md_report(results, run_path, args.judge_model)
    print(f"\nReport -> {out}")
    return 0


if __name__ == "__main__":
    import asyncio
    sys.exit(asyncio.run(main()))
